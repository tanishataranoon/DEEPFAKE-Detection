# =========================================================================
# CONFIGURATION
# =========================================================================

PATTERN = re.compile(
    r"^(?P<cat>.+)_(?P<idx>\d+)_cam\.npy$"
)

CAT_ORDER = [
    "correct_real",
    "correct_fake",
    "false_fake",
    "false_real",
    "uncertain",
    "manual",
]

# Rule of thumb only.
# Mean absolute Spearman below this threshold = PASS.
SAME_THRESHOLD = 0.5


# =========================================================================
# NUMERIC HELPERS
# =========================================================================

def rankdata(a):
    """
    Compute average ranks for tied values.
    Similar to scipy.stats.rankdata(method='average').
    """
    a = np.asarray(a, dtype=float).ravel()

    if len(a) == 0:
        return np.array([])

    order = np.argsort(a, kind="mergesort")

    ranks = np.empty(len(a), dtype=float)
    ranks[order] = np.arange(len(a), dtype=float)

    sorted_values = a[order]

    i = 0

    while i < len(a):
        j = i

        while (
            j + 1 < len(a)
            and sorted_values[j + 1] == sorted_values[i]
        ):
            j += 1

        if j > i:
            average_rank = (i + j) / 2.0
            ranks[order[i:j + 1]] = average_rank

        i = j + 1

    return ranks


def spearman(a, b):
    """
    Spearman rank correlation between two arrays.
    """
    ra = rankdata(a)
    rb = rankdata(b)

    if len(ra) == 0 or len(rb) == 0:
        return float("nan")

    if ra.std() == 0 or rb.std() == 0:
        return float("nan")

    return float(np.corrcoef(ra, rb)[0, 1])


def top_fraction_iou(a, b, frac=0.10):
    """
    Intersection-over-Union between the top fraction of
    attribution values in two CAMs.
    """
    a = np.asarray(a).ravel()
    b = np.asarray(b).ravel()

    if len(a) == 0 or len(b) == 0:
        return float("nan")

    ma = a >= np.quantile(a, 1 - frac)
    mb = b >= np.quantile(b, 1 - frac)

    union = (ma | mb).sum()

    if union == 0:
        return float("nan")

    return float((ma & mb).sum() / union)


def top_mass(cam, frac=0.10):
    """
    Share of each frame's CAM mass contained in its
    top 10% patches.

    Higher value = more concentrated attribution.
    """
    cam = np.asarray(cam, dtype=float)

    values = []

    for frame in cam.reshape(cam.shape[0], -1):

        total = frame.sum()

        if total > 0:

            k = max(
                1,
                int(round(frac * frame.size))
            )

            top_values = np.sort(frame)[::-1][:k]

            values.append(
                top_values.sum() / total
            )

    return float(np.mean(values)) if values else float("nan")


def norm_entropy(cam):
    """
    Mean normalized entropy per frame.

    0 = very concentrated / hotspot-like
    1 = very diffuse
    """
    cam = np.asarray(cam, dtype=float)

    values = []

    for frame in cam.reshape(cam.shape[0], -1):

        total = frame.sum()

        if total > 0:

            p = frame / total

            p = p[p > 0]

            entropy = -np.sum(
                p * np.log(p)
            )

            normalized = entropy / np.log(frame.size)

            values.append(float(normalized))

    return float(np.mean(values)) if values else float("nan")


def region_masses(cam, border=2):
    """
    Calculate:
        border_share
        centre_share

    Border = outer 2-patch ring.
    """
    cam = np.asarray(cam, dtype=float)

    g = cam.shape[-1]

    total = cam.sum()

    if total <= 0:
        return float("nan"), float("nan")

    inner = cam[
        :,
        border:g - border,
        border:g - border
    ].sum()

    centre = cam[
        :,
        g // 4:g - g // 4,
        g // 4:g - g // 4
    ].sum()

    border_share = (total - inner) / total
    centre_share = centre / total

    return (
        float(border_share),
        float(centre_share),
    )


# =========================================================================
# LOADING
# =========================================================================

def load_run(directory):
    """
    Load:
        summary.csv
        *_cam.npy
    """
    directory = Path(directory)

    if not directory.exists():
        raise FileNotFoundError(
            f"XAI directory not found:\n{directory}"
        )

    summary = {}

    summary_path = directory / "summary.csv"

    if not summary_path.exists():
        raise FileNotFoundError(
            f"summary.csv not found:\n{summary_path}"
        )

    with open(
        summary_path,
        newline="",
        encoding="utf-8"
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:

            summary[int(row["index"])] = row

    cams = {}

    for path in sorted(
        directory.glob("*_cam.npy")
    ):

        match = PATTERN.match(path.name)

        if match:

            index = int(match["idx"])

            category = match["cat"]

            cams[index] = (
                category,
                np.load(path)
            )

    return summary, cams


def safe_float(value):
    """
    Convert CSV value to float.
    """
    try:
        return float(value)
    except (TypeError, ValueError):
        return float("nan")


# =========================================================================
# MAIN
# =========================================================================

def main():

    parser = argparse.ArgumentParser(
        description=(
            "Analyze Appearance XAI outputs "
            "without loading the model."
        )
    )

    parser.add_argument(
        "--trained",
        required=True,
        help="Directory containing trained-model XAI outputs."
    )

    parser.add_argument(
        "--random",
        default=None,
        help=(
            "Directory containing randomized-model outputs. "
            "Default: <trained>_RANDOMIZED"
        )
    )

    parser.add_argument(
        "--out",
        default=None,
        help="Output report directory."
    )

    parser.add_argument(
        "--print-indices",
        action="store_true",
        help=(
            "Print command for rerunning exactly "
            "the same indices with randomized weights."
        )
    )

    parser.add_argument(
        "--method",
        default="gradcam",
        help="CAM method used for randomized rerun."
    )

    parser.add_argument(
        "--target",
        default="pred",
        help="XAI target used during randomized rerun."
    )

    parser.add_argument(
        "--grid-per-cat",
        type=int,
        default=1,
        help="Number of report examples per category."
    )

    args = parser.parse_args()

    # ---------------------------------------------------------------------
    # Load trained run
    # ---------------------------------------------------------------------

    trained_dir = Path(args.trained)

    summary_trained, cams_trained = load_run(
        trained_dir
    )

    # ---------------------------------------------------------------------
    # Print randomized-model command
    # ---------------------------------------------------------------------

    if args.print_indices:

        indices = " ".join(
            str(index)
            for index in sorted(cams_trained)
        )

        print()
        print(
            "Re-run the SAME clips on a randomized model."
        )
        print(
            "Do NOT use --auto-pick because "
            "randomized predictions differ."
        )
        print()

        print(
            "python "
            "evalution/appearanch_branch/xai/"
            "appearance_xai.py "
            f"--indices {indices} "
            f"--randomize "
            f"--method {args.method} "
            f"--target {args.target} "
            f"--tag {trained_dir.name}"
        )

        print()

        return

    # ---------------------------------------------------------------------
    # Randomized directory
    # ---------------------------------------------------------------------

    if args.random:

        randomized_dir = Path(args.random)

    else:

        randomized_dir = trained_dir.with_name(
            trained_dir.name + "_RANDOMIZED"
        )

    randomized_exists = (
        randomized_dir / "summary.csv"
    ).exists()

    if randomized_exists:

        _, cams_randomized = load_run(
            randomized_dir
        )

    else:

        cams_randomized = {}

    # ---------------------------------------------------------------------
    # Output directory
    # ---------------------------------------------------------------------

    if args.out:

        output_dir = Path(args.out)

    else:

        output_dir = (
            trained_dir / "day2_report"
        )

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    print()
    print("=" * 72)
    print("APPEARANCE XAI - DAY 2 ANALYSIS")
    print("=" * 72)

    print(
        f"trained : {trained_dir}"
        f" ({len(cams_trained)} clips)"
    )

    if randomized_exists:

        print(
            f"random  : {randomized_dir}"
            f" ({len(cams_randomized)} clips)"
        )

    else:

        print(
            f"random  : {randomized_dir}"
            " (NOT FOUND - sanity check skipped)"
        )

    print(
        f"output  : {output_dir}"
    )

    # =====================================================================
    # PER-CLIP METRICS
    # =====================================================================

    rows = []

    for index, (category, cam) in sorted(
        cams_trained.items()
    ):

        summary = summary_trained.get(
            index,
            {}
        )

        border_share, centre_share = (
            region_masses(cam)
        )

        row = {
            "index": index,
            "category": category,
            "true": summary.get(
                "true_label",
                ""
            ),
            "pred": summary.get(
                "prediction",
                ""
            ),
            "uncertainty": safe_float(
                summary.get(
                    "uncertainty",
                    "nan"
                )
            ),
            "top10_mass": top_mass(cam),
            "entropy": norm_entropy(cam),
            "border_share": border_share,
            "centre_share": centre_share,
        }

        # -------------------------------------------------------------
        # Attention vs CAM frame importance
        # -------------------------------------------------------------

        try:

            attention = np.array(
                json.loads(
                    summary["attention"]
                )
            )

            cam_importance = np.array(
                json.loads(
                    summary["cam_importance"]
                )
            )

            row[
                "attn_vs_cam_frames"
            ] = spearman(
                attention,
                cam_importance
            )

        except Exception:

            row[
                "attn_vs_cam_frames"
            ] = float("nan")

        # -------------------------------------------------------------
        # Randomized-model comparison
        # -------------------------------------------------------------

        if index in cams_randomized:

            cam_random = cams_randomized[
                index
            ][1]

            row[
                "rand_vs_trained_spearman"
            ] = spearman(
                cam,
                cam_random
            )

            row[
                "rand_vs_trained_iou10"
            ] = top_fraction_iou(
                cam,
                cam_random
            )

            row[
                "rand_border_share"
            ] = region_masses(
                cam_random
            )[0]

        rows.append(row)

    # =====================================================================
    # FILL MISSING COLUMNS
    # =====================================================================

    if not rows:

        raise RuntimeError(
            "No *_cam.npy files were found "
            "in the trained XAI directory."
        )

    keys = list(rows[0].keys())

    for row in rows:

        for key in keys:

            row.setdefault(
                key,
                float("nan")
            )

    # =====================================================================
    # SAVE CSV
    # =====================================================================

    metrics_path = (
        output_dir / "day2_metrics.csv"
    )

    with open(
        metrics_path,
        "w",
        newline="",
        encoding="utf-8"
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=keys
        )

        writer.writeheader()

        for row in rows:

            cleaned = {}

            for key, value in row.items():

                if isinstance(value, float):

                    cleaned[key] = round(
                        value,
                        4
                    )

                else:

                    cleaned[key] = value

            writer.writerow(cleaned)

    # =====================================================================
    # TEXT SUMMARY
    # =====================================================================

    lines = [
        "APPEARANCE XAI - DAY 2 SUMMARY",
        "=" * 60,
        f"clips analysed: {len(rows)}",
        "",
        "Per category (means; descriptive only, n is tiny):",
        (
            f"{'category':14s} "
            f"{'n':>2s} "
            f"{'u':>6s} "
            f"{'top10':>6s} "
            f"{'entropy':>8s} "
            f"{'border':>7s} "
            f"{'attn~cam':>9s}"
        ),
    ]

    # ---------------------------------------------------------------------
    # Category means
    # ---------------------------------------------------------------------

    for category in CAT_ORDER:

        group = [
            row
            for row in rows
            if row["category"] == category
        ]

        if not group:
            continue

        def mean_metric(key):

            values = [
                row[key]
                for row in group
            ]

            return np.nanmean(values)

        lines.append(
            f"{category:14s} "
            f"{len(group):2d} "
            f"{mean_metric('uncertainty'):6.3f} "
            f"{mean_metric('top10_mass'):6.3f} "
            f"{mean_metric('entropy'):8.3f} "
            f"{mean_metric('border_share'):7.3f} "
            f"{mean_metric('attn_vs_cam_frames'):9.3f}"
        )

    lines += [
        "",
        (
            "top10 = share of CAM mass in the top "
            "10% patches (higher = more focused)"
        ),
        (
            "entropy = 0 single hotspot .. "
            "1 fully diffuse"
        ),
        (
            "border = share in the outer "
            "2-patch ring"
        ),
        (
            "attn~cam = Spearman between "
            "AttentionPooling frame weights "
            "and per-frame CAM mass"
        ),
        "",
    ]

    # =====================================================================
    # RANDOMIZED SANITY CHECK
    # =====================================================================

    if randomized_exists:

        spearman_values = np.array([
            row["rand_vs_trained_spearman"]
            for row in rows
        ])

        iou_values = np.array([
            row["rand_vs_trained_iou10"]
            for row in rows
        ])

        mean_spearman = np.nanmean(
            spearman_values
        )

        mean_abs_spearman = np.nanmean(
            np.abs(spearman_values)
        )

        max_spearman = np.nanmax(
            spearman_values
        )

        mean_iou = np.nanmean(
            iou_values
        )

        lines += [
            "SANITY CHECK "
            "(trained vs randomised weights, same clips)",
            (
                f"  Spearman: mean "
                f"{mean_spearman:.3f}  "
                f"mean|.| "
                f"{mean_abs_spearman:.3f}  "
                f"max "
                f"{max_spearman:.3f}"
            ),
            (
                f"  top-10% IoU: "
                f"mean {mean_iou:.3f}"
            ),
        ]

        if (
            mean_abs_spearman
            < SAME_THRESHOLD
        ):

            verdict = (
                "PASS: maps from the trained model "
                "are clearly different from "
                "randomised-model maps."
            )

        else:

            verdict = (
                "WARNING: maps are similar to "
                "randomised-model maps. They may "
                "reflect image structure, not what "
                "was learned. Try --block-index -4 "
                "or --method layercam before using "
                "them in the report."
            )

        lines += [
            "  " + verdict,
            (
                f"  (threshold {SAME_THRESHOLD} "
                "is a rule of thumb, not a standard)"
            ),
            "",
        ]

    else:

        lines += [
            "SANITY CHECK skipped.",
            (
                "Run --print-indices, execute the "
                "printed randomized-model command, "
                "then run this analysis again."
            ),
            "",
        ]

    summary_text = "\n".join(lines)

    summary_path = (
        output_dir / "day2_summary.txt"
    )

    summary_path.write_text(
        summary_text,
        encoding="utf-8"
    )

    print()
    print(summary_text)

    # =====================================================================
    # SANITY CHECK FIGURE
    # =====================================================================

    if randomized_exists:

        selected = [
            row["index"]
            for row in rows
            if row["index"] in cams_randomized
        ][:4]

        if selected:

            fig, axes = plt.subplots(
                len(selected),
                2,
                figsize=(
                    5.2,
                    2.6 * len(selected)
                ),
                squeeze=False
            )

            for i, index in enumerate(
                selected
            ):

                cam_trained = (
                    cams_trained[index][1]
                )

                cam_random = (
                    cams_randomized[index][1]
                )

                # Select the frame with
                # maximum trained CAM mass.
                frame = int(
                    np.argmax(
                        cam_trained.reshape(
                            cam_trained.shape[0],
                            -1
                        ).sum(axis=1)
                    )
                )

                correlation = spearman(
                    cam_trained,
                    cam_random
                )

                axes[i, 0].imshow(
                    cam_trained[frame],
                    cmap="jet"
                )

                axes[i, 0].set_title(
                    (
                        f"trained  idx {index}  "
                        f"frame {frame + 1}"
                    ),
                    fontsize=8
                )

                axes[i, 1].imshow(
                    cam_random[frame],
                    cmap="jet"
                )

                axes[i, 1].set_title(
                    (
                        f"randomised  "
                        f"(Spearman "
                        f"{correlation:.2f})"
                    ),
                    fontsize=8
                )

                for axis in axes[i]:

                    axis.set_xticks([])
                    axis.set_yticks([])

            fig.suptitle(
                "Sanity check: 16x16 attribution maps",
                fontsize=10
            )

            fig.tight_layout()

            fig.savefig(
                output_dir / "sanity_check.png",
                dpi=150
            )

            plt.close(fig)

    # =====================================================================
    # REPORT GRID
    # =====================================================================

    report_picks = []

    for category in CAT_ORDER:

        category_rows = [
            row
            for row in rows
            if row["category"] == category
        ]

        selected = category_rows[
            :args.grid_per_cat
        ]

        for row in selected:

            png_path = (
                trained_dir
                / f"{category}_{row['index']}.png"
            )

            if png_path.exists():

                report_picks.append(
                    (
                        category,
                        png_path
                    )
                )

    if report_picks:

        fig, axes = plt.subplots(
            len(report_picks),
            1,
            figsize=(
                13,
                4.2 * len(report_picks)
            ),
            squeeze=False
        )

        for i, (
            category,
            png_path
        ) in enumerate(report_picks):

            image = mpimg.imread(
                png_path
            )

            axes[i, 0].imshow(image)

            axes[i, 0].axis("off")

            axes[i, 0].set_title(
                category.replace(
                    "_",
                    " "
                ).upper(),
                loc="left",
                fontsize=10,
                fontweight="bold"
            )

        fig.tight_layout()

        fig.savefig(
            output_dir / "report_grid.png",
            dpi=130
        )

        plt.close(fig)

    # =====================================================================
    # COMPLETE
    # =====================================================================

    print()
    print("=" * 72)
    print("DAY 2 XAI ANALYSIS COMPLETE")
    print("=" * 72)

    print(
        f"Metrics : "
        f"{output_dir / 'day2_metrics.csv'}"
    )

    print(
        f"Summary : "
        f"{output_dir / 'day2_summary.txt'}"
    )

    if randomized_exists:

        print(
            f"Sanity  : "
            f"{output_dir / 'sanity_check.png'}"
        )

    if report_picks:

        print(
            f"Grid    : "
            f"{output_dir / 'report_grid.png'}"
        )

    print()


if __name__ == "__main__":
    main()